function readyHandouts(s){const f=s.campaign?.facts||{};return {H01:!!f.infoKnown,H02:!!f.warehouseSurvey,H03:!!f.warehouseSurvey,H04:!!f.waterwayNoteSeen,H05:!!f.finalRollCall,H06:true};}
export function availableHandouts(s){const ready=readyHandouts(s);return handouts.filter(h=>ready[h.id]).map(h=>({...h,cue:cues[h.id]}));}
export function publishHandout(s,id){
 const entry=handouts.find(h=>h.id===id);if(!entry)throw Error('没有这份手札。');
 s.journal||=[];s.log||=[];
 if(s.journal.some(j=>j.sourceHandout===id))return false;
 const ready=readyHandouts(s);
 if(!ready[id])throw Error('这份材料尚未在实际场景中发现或开始商谈，不能提前发放。');
 s.journal.push({title:entry.title,text:entry.text,sourceHandout:id,publishedAt:new Date().toISOString()});
 s.log.push({id:++s.logSeq,kind:'story',text:`主持人出示了《${entry.title}》，已收入手记。`,time:new Date().toISOString()});
 return true;
}
